"""Emit an opt-in shell script that creates backdated git commits.

This is the "powerful half" of the tool and it is deliberately gated behind
an explicit ``--emit-git-script`` flag plus a loud warning header inside the
generated file. The script only ever *adds empty commits with backdated
timestamps* to whatever repo it is run in — it never pushes anything.

Dates and commit messages are quoted with :func:`shlex.quote`, so apostrophes
or quotes in a message cannot break out of the shell string.
"""

from __future__ import annotations

import random
import shlex
from datetime import date
from pathlib import Path

from .generator import DayActivity

#: Placeholder messages rotated through when the caller doesn't supply any.
DEFAULT_MESSAGES: tuple[str, ...] = (
    "feat: add contribution heatmap parser",
    "fix: handle empty activity ranges",
    "refactor: extract week-column math",
    "docs: document the profile options",
    "test: cover leap-year date ranges",
    "chore: tidy up the report writer",
    "feat: add streak detection to summary",
    "fix: clamp negative commit counts",
)

HEADER_TEMPLATE = """\
#!/usr/bin/env bash
# ==============================================================================
#  fake_commits.sh — generated by gh-activity-forge
#
#  !! WARNING: THIS SCRIPT CREATES FAKE, BACKDATED COMMITS !!
#
#  Use it ONLY on throwaway/demo repos to preview a contribution graph.
#  NEVER push the resulting history to a repo presented as your real work —
#  green squares ≠ real engineering, and anyone can open the commits behind
#  the squares to see what they really contain (nothing).
#
#  profile: {profile} | range: {start} .. {end} | seed: {seed}
# ==============================================================================
set -euo pipefail

if ! git rev-parse --is-inside-work-tree >/dev/null 2>&1; then
  echo 'fake_commits.sh: this is not a git repository — run it inside one.' >&2
  exit 1
fi
if ! git config user.email >/dev/null 2>&1; then
  echo 'fake_commits.sh: git user.email is not set — set it first.' >&2
  exit 1
fi

"""

_FOOTER_TEMPLATE = """
echo 'fake_commits.sh: created {total} backdated commits.'
echo 'Reminder: these are demo squares only — do not present them as real work.'
"""


def _commit_time(day: date, rng: random.Random) -> str:
    """A believable working-hours timestamp for ``day`` (local time, ISO)."""
    hour = rng.randint(8, 21)
    minute = rng.randint(0, 59)
    second = rng.randint(0, 59)
    return f"{day.isoformat()}T{hour:02d}:{minute:02d}:{second:02d}"


def render_git_script(
    activities: list[DayActivity],
    *,
    profile: str = "random",
    seed: int = 42,
    messages: tuple[str, ...] | None = None,
) -> str:
    """Render the full ``fake_commits.sh`` text for this activity plan.

    One ``git commit --allow-empty`` per non-zero day-count, each with
    ``GIT_AUTHOR_DATE``/``GIT_COMMITTER_DATE`` backdated to that day.
    Deterministic for a given (plan, seed): the RNG only picks times and
    rotates messages.
    """
    pool = messages if messages is not None else DEFAULT_MESSAGES
    if not pool:
        raise ValueError("messages must not be empty")
    if not activities:
        raise ValueError("cannot emit a git script from an empty activity list")

    rng = random.Random(f"gh-activity-forge:{seed}")
    lines = [
        HEADER_TEMPLATE.format(
            profile=profile,
            start=activities[0].date.isoformat(),
            end=activities[-1].date.isoformat(),
            seed=seed,
        )
    ]

    total = 0
    for activity in activities:
        if activity.commit_count <= 0:
            continue
        lines.append(
            f"# {activity.date.isoformat()} — {activity.commit_count} commits"
        )
        for _ in range(activity.commit_count):
            stamp = _commit_time(activity.date, rng)
            message = shlex.quote(rng.choice(pool))
            lines.append(
                f"GIT_AUTHOR_DATE={shlex.quote(stamp)} "
                f"GIT_COMMITTER_DATE={shlex.quote(stamp)} \\"
            )
            lines.append(
                f"  git commit --allow-empty -q -m {message}"
            )
            total += 1
        lines.append("")

    lines.append(
        _FOOTER_TEMPLATE.format(total=total)
    )
    return "\n".join(lines)


def write_git_script(
    path: Path,
    activities: list[DayActivity],
    *,
    profile: str = "random",
    seed: int = 42,
    messages: tuple[str, ...] | None = None,
) -> Path:
    """Write the script to ``path`` and make it executable."""
    text = render_git_script(
        activities, profile=profile, seed=seed, messages=messages
    )
    path.write_text(text, encoding="utf-8")
    path.chmod(path.stat().st_mode | 0o111)
    return path
